package embedts

import "golang.org/x/sys/unix"

// defaultFsTotalBytes 返回 dir 所在文件系统的总字节数（statfs Blocks × Bsize）。
// defaultFsTotalBytes returns the total bytes of the filesystem holding dir (statfs Blocks × Bsize).
func defaultFsTotalBytes(dir string) (int64, error) {
	var st unix.Statfs_t
	if err := unix.Statfs(dir, &st); err != nil {
		return 0, err
	}
	return int64(st.Blocks) * int64(st.Bsize), nil
}
