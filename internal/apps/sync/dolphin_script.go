package sync

import (
	"fmt"
	"sort"
	"strings"
	"time"
)

const (
	defaultDolphinCLITimeout = "6h"
	// defaultDolphinWorkerGroup 必须是 Dolphin 自带的 default；真实单机没有 stx-workers。
	// defaultDolphinWorkerGroup must be Dolphin's built-in default; a real standalone has no stx-workers group.
	defaultDolphinWorkerGroup = "default"
	defaultDolphinEnvironment = "stx-cli-prod"
	// dolphinScheduleTimePlaceholder 必须保持为 Dolphin 原样占位符，不能在 Go 里插值。
	// dolphinScheduleTimePlaceholder must stay a Dolphin placeholder and must not be interpolated by Go.
	dolphinScheduleTimePlaceholder     = `${system.datetime}`
	dolphinWorkflowInstancePlaceholder = `${system.workflow.instance.id}`
	dolphinTaskCodePlaceholder         = `${system.task.definition.code}`
)

// BuildDolphinShellScript 生成 SHELL 节点脚本；没有覆盖变量时不追加 --var。
// BuildDolphinShellScript builds the SHELL node script and omits --var when there are no overrides.
func BuildDolphinShellScript(task *Task, timeout string, variables map[string]string, workerGroup, environment string) *DolphinScriptResult {
	if task == nil {
		return &DolphinScriptResult{
			Timeout:     defaultString(timeout, defaultDolphinCLITimeout),
			WorkerGroup: defaultString(workerGroup, defaultDolphinWorkerGroup),
			Environment: defaultString(environment, defaultDolphinEnvironment),
		}
	}
	timeout = defaultString(strings.TrimSpace(timeout), defaultDolphinCLITimeout)
	workerGroup = defaultString(strings.TrimSpace(workerGroup), defaultDolphinWorkerGroup)
	environment = defaultString(strings.TrimSpace(environment), defaultDolphinEnvironment)

	ref := fmt.Sprintf("ds:%s:%s", dolphinWorkflowInstancePlaceholder, dolphinTaskCodePlaceholder)
	waitFlags := "--wait --confirm"
	if task.Mode == TaskModeStreaming {
		// 实时任务不能在 CLI 退出时停作业，脚本里显式关闭 close-job。
		// Streaming jobs must keep running after the CLI exits, so the script turns close-job off.
		waitFlags = "--wait --close-job=false --confirm"
	}
	lines := []string{
		fmt.Sprintf("# 由 STX 生成（任务 #%d %s），重新推送会覆盖", task.ID, strings.TrimSpace(task.Name)),
		fmt.Sprintf("# Generated by STX (task #%d %s); a later push overwrites this node", task.ID, strings.TrimSpace(task.Name)),
		fmt.Sprintf("exec stx sync task submit %d %s \\", task.ID, waitFlags),
		fmt.Sprintf("  --external-ref %q \\", ref),
		fmt.Sprintf("  --schedule-time %q \\", dolphinScheduleTimePlaceholder),
		fmt.Sprintf("  --timeout %s", timeout),
	}

	keys := make([]string, 0, len(variables))
	cleanVars := map[string]string{}
	for key, value := range variables {
		name := strings.TrimSpace(key)
		if name == "" || isUnreplacedPlaceholder(value) {
			continue
		}
		keys = append(keys, name)
		cleanVars[name] = value
	}
	sort.Strings(keys)
	if len(keys) > 0 {
		lines[len(lines)-1] = lines[len(lines)-1] + " \\"
		for index, key := range keys {
			suffix := ""
			if index < len(keys)-1 {
				suffix = " \\"
			}
			lines = append(lines, fmt.Sprintf("  --var %s=%s%s", key, shellSingleToken(cleanVars[key]), suffix))
		}
	}

	// env_notes 只提醒 Worker 由用户自行绑定登录令牌；推送不会签发或写入 STX_TOKEN。
	// env_notes only remind the operator to bind the login token; push never issues or writes STX_TOKEN.
	envNotes := strings.Join([]string{
		"# Worker 环境 stx-cli-prod 由用户自行绑定 STX 登录令牌；推送只写 SHELL 脚本，不签发、不写入 STX_TOKEN。",
		"# The stx-cli-prod worker binds the STX login token itself; push only writes the SHELL script and does not issue or set STX_TOKEN.",
		"# 用户侧：管理员签发 stx_ 后，在 Worker 上执行 stx login --token，或自行设置 STX_SERVER / STX_TOKEN。",
		"# Operator side: after an admin issues stx_, bind it on the worker with stx login --token or STX_SERVER / STX_TOKEN.",
	}, "\n")

	return &DolphinScriptResult{
		Script:      strings.Join(lines, "\n") + "\n",
		EnvNotes:    envNotes + "\n",
		Timeout:     timeout,
		WorkerGroup: workerGroup,
		Environment: environment,
		Variables:   cleanVars,
	}
}

func shellSingleToken(value string) string {
	if value == "" {
		return `""`
	}
	if strings.ContainsAny(value, " \t\n\"'`$") {
		return "'" + strings.ReplaceAll(value, "'", `'"'"'`) + "'"
	}
	return value
}

func dolphinNodeTimeoutMinutes(timeout string) int {
	parsed, err := time.ParseDuration(defaultString(strings.TrimSpace(timeout), defaultDolphinCLITimeout))
	if err != nil || parsed <= 0 {
		parsed = 6 * time.Hour
	}
	minutes := int(parsed.Minutes()) + 10
	if minutes < 11 {
		return 11
	}
	return minutes
}
